static void check(bool ok,const juce::String& why) {if(!ok) throw std::runtime_error(why.toStdString());}

static void checkValues(const frostbite::Values& actual,const frostbite::Values& expected,const juce::String& context) {
    for(size_t n=0;n<expected.size();++n)
        check(std::abs(actual[n]-expected[n])<.002f,context+": "+frostbite::parameterInfo[n].id);
}

// This list is intentionally independent of ParameterInfo: it is the persisted
// automation/state contract, not a second description of DSP behaviour.
static void checkParameterContract(FrostbiteAudioProcessor& p) {
    const std::array<const char*,34> stableIds{{
        "freeze","damage","distance","echo","abyss","motion","mix","output",
        "capture","bypass","texture","drift","freeze_level","echo_ms","echo_sync",
        "echo_division","feedback","echo_tone","width","echo_level","size","decay",
        "damping","diffusion","reverb_mod","predelay","reverb_level","drive","character",
        "damage_tone","damage_blend","motion_rate","motion_depth","input"
    }};
    check(p.getParameters().size()==int(frostbite::Count),"persisted parameter count changed");
    for(size_t i=0;i<stableIds.size();++i) {
        auto* parameter=p.state.getParameter(stableIds[i]);
        check(parameter!=nullptr,"missing stable parameter ID: "+juce::String(stableIds[i]));
        check(p.getParameters()[int(i)]==parameter,"automation parameter order changed: "+juce::String(stableIds[i]));
        check(parameter->getVersionHint()==1,"parameter version changed: "+juce::String(stableIds[i]));
    }
    check(p.getBypassParameter()==p.state.getParameter("bypass"),"host bypass parameter mismatch");
}

static juce::File factoryDirectory() {
    for(auto start:{juce::File::getCurrentWorkingDirectory(),
                    juce::File::getSpecialLocation(juce::File::currentExecutableFile).getParentDirectory(),
                    juce::File::getCurrentWorkingDirectory().getChildFile(__FILE__).getParentDirectory()}) {
        for(int i=0;i<10;++i) {
            const auto directory=start.getChildFile("Presets/Factory");
            if(directory.isDirectory() && start.getChildFile("Source/Parameters.cpp").existsAsFile()) return directory;
            const auto parent=start.getParentDirectory();
            if(parent==start) break;
            start=parent;
        }
    }
    throw std::runtime_error("could not locate repository factory presets");
}

static void checkFactoryFiles(FrostbiteAudioProcessor& p) {
    const auto directory=factoryDirectory();
    check(directory.findChildFiles(juce::File::findFiles,true,"*.frostbite").size()==p.getNumPrograms(),"factory file count mismatch");
    for(int program=0;program<p.getNumPrograms();++program) {
        const auto& preset=frostbite::factoryPresets()[size_t(program)];
        const auto file=(program<8?directory:directory.getChildFile("V2")).getChildFile(juce::String(preset.name)+".frostbite");
        auto xml=juce::XmlDocument::parse(file);
        check(xml!=nullptr,"cannot parse shipped preset: "+file.getFileName());
        const auto tree=juce::ValueTree::fromXml(*xml);
        check(tree.hasType("FrostbiteState") && int(tree.getProperty("schema"))==(program<8?1:2),"factory schema mismatch");
        check(tree.getProperty("presetName").toString()==preset.name,"factory name mismatch");
        std::set<juce::String> ids;
        for(auto child:tree) {
            const auto id=child.getProperty("id").toString();
            check(p.state.getParameter(id)!=nullptr,"unknown factory parameter: "+id);
            check(ids.insert(id).second,"duplicate factory parameter: "+id);
        }
        check(ids.size()==(program<8?34:frostbite::Count),"incomplete factory preset: "+file.getFileName());
        // Load the checked-in files, not files generated by the code under test.
        check(p.loadPreset(file).wasOk(),"load shipped preset: "+file.getFileName());
        checkValues(p.values(),preset.values,"shipped preset "+juce::String(preset.name));
        check(p.presetName()==preset.name,"shipped preset name restore");
        check(p.values()[frostbite::Capture]==0,"shipped preset unexpectedly captures");
    }
}

static void restoreStateTree(FrostbiteAudioProcessor& p,const juce::ValueTree& tree) {
    juce::MemoryBlock binary;
    auto xml=tree.createXml();
    check(xml!=nullptr,"test state serialisation");
    juce::AudioProcessor::copyXmlToBinary(*xml,binary);
    p.setStateInformation(binary.getData(),int(binary.getSize()));
}

static void checkStateCompatibility() {
    FrostbiteAudioProcessor source,restored;
    source.setCurrentProgram(6);
    auto custom=source.values();
    custom[frostbite::Input]=4.2f;custom[frostbite::Output]=-1.7f;
    custom[frostbite::MotionRate]=1.73f;custom[frostbite::EchoSync]=0;
    custom[frostbite::EchoMs]=731;custom[frostbite::Capture]=1;
    source.applyValues(custom);
    juce::MemoryBlock binary;source.getStateInformation(binary);
    restored.setStateInformation(binary.getData(),int(binary.getSize()));
    auto expected=source.values();expected[frostbite::Capture]=0;
    checkValues(restored.values(),expected,"custom host state roundtrip");
    check(restored.getCurrentProgram()==6 && restored.presetName()=="Endless Winter","host state metadata roundtrip");
    check(source.values()[frostbite::Capture]==1,"serialisation changed running capture control");

    const auto before=restored.values();
    auto unsupported=source.state.copyState();unsupported.setProperty("schema",3,nullptr);
    restoreStateTree(restored,unsupported);
    checkValues(restored.values(),before,"future schema altered values");
    check(restored.getCurrentProgram()==6 && restored.presetName()=="Endless Winter","future schema altered metadata");
    restoreStateTree(restored,juce::ValueTree("UnrelatedPlugin"));
    checkValues(restored.values(),before,"unrelated state altered values");
    restored.setStateInformation(nullptr,0);
    checkValues(restored.values(),before,"empty state altered values");

    // Historic/partial states recover by stable ID, independent of child order;
    // absent IDs default and future unknown IDs do not move existing values.
    juce::ValueTree legacy("FrostbiteState");
    for(auto [id,value]:std::initializer_list<std::pair<const char*,float>>{
            {"output",-7.4f},{"future_parameter",.91f},{"freeze",.29f},{"capture",1.0f}}) {
        juce::ValueTree child("PARAM");child.setProperty("id",id,nullptr);
        child.setProperty("value",value,nullptr);legacy.addChild(child,-1,nullptr);
    }
    restoreStateTree(restored,legacy);
    expected=frostbite::legacyDefaults();expected[frostbite::Output]=-7.4f;expected[frostbite::Freeze]=.29f;
    checkValues(restored.values(),expected,"legacy partial state");
    check(restored.presetName()=="User","legacy state fallback name");
    legacy.setProperty("schema",2,nullptr);restoreStateTree(restored,legacy);
    checkValues(restored.values(),expected,"schema2 without voicing must be Legacy");
    source.restoreDefaults();source.setCurrentProgram(17);source.getStateInformation(binary);
    restored.setStateInformation(binary.getData(),int(binary.getSize()));
    checkValues(restored.values(),source.values(),"explicit V2 state roundtrip");
    check(restored.values()[frostbite::Voicing]==1 && restored.getCurrentProgram()==17,"V2 voicing/program lost");

}

static void checkRoutingAndBypass() {
    for(double sampleRate:{44100.0,48000.0,96000.0}) for(int blockSize:{1,64,128,256,512,1024}) for(bool mono:{false,true}) {
        FrostbiteAudioProcessor p;
        auto layout=p.getBusesLayout();
        layout.inputBuses.set(0,mono?juce::AudioChannelSet::mono():juce::AudioChannelSet::stereo());
        check(p.setBusesLayout(layout),"supported input layout rejected");
        auto v=p.values();v[frostbite::Mix]=0;v[frostbite::Output]=0;
        v[frostbite::Input]=12;v[frostbite::Damage]=1;v[frostbite::Distance]=1;
        p.applyValues(v);p.prepareToPlay(sampleRate,blockSize);
        check(p.getLatencySamples()==0,"unexpected latency on dry path");
        juce::AudioBuffer<float> audio(2,blockSize),expected(2,blockSize);juce::MidiBuffer midi;
        const auto fill=[&](int count,int offset) {
            for(int n=0;n<count;++n) {
                const float l=.61f*std::sin(float(offset+n)*.117f)+.04f;
                const float r=mono?l:.37f*std::cos(float(offset+n)*.071f)-.025f;
                audio.setSample(0,n,l);audio.setSample(1,n,mono?-.87f:r);
                expected.setSample(0,n,l);expected.setSample(1,n,r);
            }
        };
        const auto unity=[&](int count,const char* reason) {
            for(int c=0;c<2;++c) for(int n=0;n<count;++n)
                check(std::abs(audio.getSample(c,n)-expected.getSample(c,n))<1e-6f,reason);
        };
        for(int block=0;block<4;++block) {
            const int count=block%2==0?blockSize:std::max(1,blockSize-17);
            fill(count,block*blockSize);
            float* channels[]{audio.getWritePointer(0),audio.getWritePointer(1)};
            juce::AudioBuffer<float> view(channels,2,count);
            p.processBlock(view,midi);unity(count,"dry unity/stereo routing mismatch");
        }
        // The host's bypass callback must ignore both gain trims and effect mix.
        v[frostbite::Mix]=1;v[frostbite::Output]=-24;p.applyValues(v);
        p.prepareToPlay(sampleRate,blockSize);
        fill(blockSize,0);p.processBlockBypassed(audio,midi);unity(blockSize,"first-block host bypass mismatch");
        check(p.values()[frostbite::Bypass]==0,"host bypass callback altered automatable parameter");
        p.prepareToPlay(sampleRate,blockSize);fill(blockSize,0);p.processBlock(audio,midi);
        const int settleBlocks=int(std::ceil(sampleRate*.4/blockSize));
        for(int block=0;block<settleBlocks;++block) {
            fill(blockSize,block*blockSize);p.processBlockBypassed(audio,midi);
        }
        unity(blockSize,"settled host bypass not unity");
        p.releaseResources();
    }
}
static void checkV2PresetTransitions() {
    for(double rate:{44100.0,48000.0,96000.0}) {
        FrostbiteAudioProcessor p;p.setCurrentProgram(8);p.prepareToPlay(rate,256);
        juce::AudioBuffer<float> audio(2,256);juce::MidiBuffer midi;float peak=0;
        const int blocks=int(rate*.4/256);
        for(int visit=0;visit<20;++visit) {
            p.setCurrentProgram(8+visit%10);
            for(int b=0;b<blocks;++b) {
                for(int n=0;n<256;++n) {
                    const double t=double((visit*blocks+b)*256+n)/rate;
                    const float x=.32f*float(std::sin(2*frostbite::pi*110*t))+.15f*float(std::sin(2*frostbite::pi*997*t));
                    audio.setSample(0,n,x);audio.setSample(1,n,x*.8f);
                }
                p.processBlock(audio,midi);
                for(int c=0;c<2;++c)for(int n=0;n<256;++n){const float x=audio.getSample(c,n);check(std::isfinite(x) && std::abs(x)<1,"V2 preset transition clipped or became invalid");peak=std::max(peak,std::abs(x));}
            }
        }
        std::cout<<"PASS V2 preset transitions rate="<<rate<<" peak="<<peak<<"\n";
    }
}
